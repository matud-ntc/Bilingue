#!/usr/bin/env python3
"""Generate Bilingue/Data_enUS.lua and Bilingue/Data_es.lua.

Sources:
  wago.tools DB2 exports of the WoW Forever client (product wowf), enUS and esMX:
    items, spells/talents, zones, maps, factions, professions, classes, races, a few creatures/objects.
  QuestieDB (Forever data + l10n lookups): NPC names and titles, quest titles, object names.

Data_enUS.lua is loaded by English clients (shows Spanish), Data_es.lua by esMX/esES clients
(shows English). Each file keeps both languages where the in-game search needs them.

  python3 scripts/build_data.py [--build 1.60.1.70862] [--questiedb PATH]
"""
import argparse
import collections
import csv
import io
import os
import re
import subprocess
import sys
import urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ADDON_DIR = os.path.join(ROOT, "Bilingue")
CACHE = os.path.join(ROOT, ".cache")
DEFAULT_BUILD = "1.60.1.70862"
DEFAULT_QUESTIEDB = os.path.expanduser(
    "~/Games/battlenet/drive_c/Program Files (x86)/World of Warcraft/_forever_/Interface/AddOns/QuestieDB")
ES = "esMX"

csv.field_size_limit(sys.maxsize)

# (table, id column, name column) -> generic name dictionary
NAME_TABLES = [
    ("SpellName", "ID", "Name_lang"),
    ("AreaTable", "ID", "AreaName_lang"),
    ("UiMap", "ID", "Name_lang"),
    ("Map", "ID", "MapName_lang"),
    ("Faction", "ID", "Name_lang"),
    ("SkillLine", "ID", "DisplayName_lang"),
    ("ChrClasses", "ID", "Name_lang"),
    ("ChrRaces", "ID", "Name_lang"),
    ("TalentTab", "ID", "Name_lang"),
    ("Creature", "ID", "Name_lang"),
    ("GameObjects", "ID", "Name_lang"),
]

JUNK = re.compile(r"\b(DND|PH|QA|UNUSED|Unused|OLD|Deprecated|DEPRECATED|TEST|Test|test|NYI|DEBUG)\b"
                  r"|^(zz|ZZ|\[|Monster - |Test )|\(\d+\)aa$")


def fetch_db2(table, locale, build):
    os.makedirs(CACHE, exist_ok=True)
    path = os.path.join(CACHE, f"{table}-{build}-{locale}.csv")
    if not os.path.exists(path):
        url = f"https://wago.tools/db2/{table}/csv?build={build}&locale={locale}"
        print("GET", url, flush=True)
        req = urllib.request.Request(url, headers={"User-Agent": "Bilingue-addon-build"})
        with urllib.request.urlopen(req) as r, open(path, "wb") as f:
            f.write(r.read())
    with open(path, encoding="utf-8") as f:
        return list(csv.DictReader(f))


def db2_pairs(table, id_col, name_col, build):
    en = {r[id_col]: r[name_col] for r in fetch_db2(table, "enUS", build)}
    es = {r[id_col]: r[name_col] for r in fetch_db2(table, ES, build)}
    return {int(k): (en[k], es[k]) for k in en if k in es}


def questie_rows(qdb, kind, locale):
    script = os.path.join(ROOT, "scripts", "dump_questie.lua")
    out = subprocess.check_output(["lua5.4", script, qdb, kind, locale], text=True)
    rows = {}
    for line in out.splitlines():
        parts = line.split("\t")
        rows[int(parts[0])] = parts[1:]
    return rows


def good(a, b):
    a, b = a.strip(), b.strip()
    return a and b and a != b and not JUNK.search(a) and not JUNK.search(b)


def lua_str(s):
    s = s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\r", "")
    return f'"{s}"'


class Names:
    """Name -> name with majority vote when a source name has several translations."""

    def __init__(self):
        self.votes = collections.defaultdict(collections.Counter)

    def add(self, src, dst, weight=1):
        if good(src, dst):
            self.votes[src.strip()][dst.strip()] += weight

    def resolved(self):
        return {k: c.most_common(1)[0][0] for k, c in self.votes.items()}


def write_table(out, field, mapping, key_is_str):
    # One closure per table: keeps every function under the client's constant limit.
    out.write(f"D.{field} = (function() return {{\n")
    for k in sorted(mapping):
        key = f"[{lua_str(k)}]" if key_is_str else f"[{k}]"
        out.write(f"{key}={lua_str(mapping[k])},\n")
    out.write("} end)()\n")


def write_data(path, locales, tables):
    with open(path, "w", encoding="utf-8", newline="\n") as out:
        out.write("-- AUTO GENERATED by scripts/build_data.py. Do not edit.\n")
        out.write("local _, ns = ...\n")
        out.write(f"if not ns.LoadsData({', '.join(lua_str(l) for l in locales)}) then return end\n")
        out.write("local D = ns.data\n")
        for field, mapping, key_is_str in tables:
            write_table(out, field, mapping, key_is_str)
    print(f"{os.path.relpath(path, ROOT)}: {os.path.getsize(path) / 1e6:.1f} MB")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--build", default=DEFAULT_BUILD)
    ap.add_argument("--questiedb", default=DEFAULT_QUESTIEDB)
    args = ap.parse_args()

    # Items by ID (exact even when two items share an English name).
    items = {i: (en, es) for i, (en, es) in db2_pairs("ItemSparse", "ID", "Display_lang", args.build).items()
             if good(en, es)}

    to_es, to_en = Names(), Names()
    for table, id_col, name_col in NAME_TABLES:
        for en, es in db2_pairs(table, id_col, name_col, args.build).values():
            to_es.add(en, es)
            to_en.add(es, en)

    npc_en, npc_es = questie_rows(args.questiedb, "npc", "enUS"), questie_rows(args.questiedb, "npc", ES)
    npcs_es, npcs_en = {}, {}
    for i, en in npc_en.items():
        es = npc_es.get(i)
        if not es:
            continue
        if good(en[0], es[0]):
            npcs_es[i], npcs_en[i] = es[0], en[0]
            to_es.add(en[0], es[0])
            to_en.add(es[0], en[0])
        if len(en) > 1 and len(es) > 1:
            to_es.add(en[1], es[1])
            to_en.add(es[1], en[1])

    obj_en, obj_es = questie_rows(args.questiedb, "object", "enUS"), questie_rows(args.questiedb, "object", ES)
    for i, en in obj_en.items():
        if i in obj_es:
            to_es.add(en[0], obj_es[i][0])
            to_en.add(obj_es[i][0], en[0])

    q_en, q_es = questie_rows(args.questiedb, "quest", "enUS"), questie_rows(args.questiedb, "quest", ES)
    quests = {i: (q_en[i][0], q_es[i][0]) for i in q_en if i in q_es and good(q_en[i][0], q_es[i][0])}

    write_data(os.path.join(ADDON_DIR, "Data_enUS.lua"), ["enUS", "enGB"], [
        ("item", {i: v[1] for i, v in items.items()}, False),
        ("itemSrc", {i: v[0] for i, v in items.items()}, False),
        ("quest", {i: v[1] for i, v in quests.items()}, False),
        ("questSrc", {i: v[0] for i, v in quests.items()}, False),
        ("npc", npcs_es, False),
        ("name", to_es.resolved(), True),
    ])
    write_data(os.path.join(ADDON_DIR, "Data_es.lua"), ["esMX", "esES"], [
        ("item", {i: v[0] for i, v in items.items()}, False),
        ("itemSrc", {i: v[1] for i, v in items.items()}, False),
        ("quest", {i: v[0] for i, v in quests.items()}, False),
        ("questSrc", {i: v[1] for i, v in quests.items()}, False),
        ("npc", npcs_en, False),
        ("name", to_en.resolved(), True),
    ])
    print(f"items {len(items)}  quests {len(quests)}  npcs {len(npcs_es)}  "
          f"names en->es {len(to_es.votes)}  es->en {len(to_en.votes)}")


if __name__ == "__main__":
    main()
